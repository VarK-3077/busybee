"""Assemble the report's recommendation, facts, scores, inferences, concerns and footer.

Facts are split by importance and capped per category: `facts_section` (section 3) lists, for
each category, at most `max_per_category` of the facts whose extraction importance is at least the
threshold, chosen by (referenced by the recommendation, a score binding, an inference or a
concern; cited from a rating-agency rationale; importance; consolidated before unscoped before
standalone; number of citations), plus every referenced fact even when that exceeds the cap. Facts
from a rating rationale qualify one importance point below the threshold, since the agency's view
bears directly on the decision. `appendix_section` lists all the rest after
the concerns, so every verified fact stays in the document but the main body stays short.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence

from markupsafe import Markup, escape

from busybee.render.fact_fields import fact_field
from busybee.render.statements import (
    concern_html,
    conflict_badge_html,
    conflicted_fact,
    humanise_category,
    inference_html,
    key_reason_html,
    rule_row_html,
    score_statement_html,
    slot_index,
    statement_with_id_html,
)
from busybee.schema.documents import DocumentKind
from busybee.schema.facts import FactCategory, FactScope, VerifiedFact
from busybee.schema.policy import Approval, InputSlot, RuleResult, ScoreResult, ScoreSpec
from busybee.schema.report import (
    Concern,
    FactGroup,
    Inference,
    KeyReason,
    Recommendation,
    Report,
)

DEFAULT_MIN_IMPORTANCE = 4
DEFAULT_MAX_PER_CATEGORY = 10
RATING_IMPORTANCE_ALLOWANCE = 1
_SCOPE_RANK = {FactScope.consolidated: 0, None: 1, FactScope.standalone: 2}

_DECISION_LABELS = {
    "approve": "Approve",
    "approve_with_conditions": "Approve with conditions",
    "decline": "Decline",
    "refer": "Refer",
    "reduce_or_decline": "Reduce the credit line or decline",
}


def _section(section_id: str, title: str, body: Markup | str) -> Markup:
    """Wrap body markup in a numbered report section."""
    return Markup(
        f'<section class="bb-section" id="{escape(section_id)}">'
        f'<h2 class="bb-h2">{escape(title)}</h2>{body}</section>'
    )


def approval_notice_html(
    *,
    approved: bool,
    policy_label: str,
    generated_by: str | None = None,
    date: str | None = None,
) -> Markup:
    """Return the unapproved-policy notice bar, or nothing when the policy is approved."""
    if approved:
        return Markup("")
    when = Markup(f" on {escape(date)}") if date else Markup("")
    origin = (
        Markup(
            f'was generated by <span class="bb-mono">{escape(generated_by)}</span>{when} and '
            "has not yet been reviewed and approved by a person."
        )
        if generated_by
        else Markup("has not yet been reviewed and approved by a person.")
    )
    return Markup(
        '<div class="bb-notice" role="note"><span>'
        "<strong>Policy formalisation not yet approved.</strong> "
        f"The Lean formalisation of {escape(policy_label)} {origin} "
        '<a href="policy.html">Read the policy explanation →</a></span></div>'
    )


def approval_line_html(approval: Approval) -> Markup:
    """Return a plain approval line for an approved policy, or nothing."""
    if not approval.approved:
        return Markup("")
    by = escape(approval.by or "a bank reviewer")
    when = Markup(f" on {escape(approval.date)}") if approval.date else Markup("")
    notes = Markup(f" {escape(approval.notes)}") if approval.notes else Markup("")
    return Markup(
        '<p class="bb-small bb-muted" role="note"><strong>Policy approved</strong> '
        f"by {by}{when}.{notes}</p>"
    )


_REASON_GROUPS = (
    ("policy_rule", "Hard rules from bank policies"),
    ("hard_fact", "Hard facts"),
    ("inference", "Inferences & guess of future"),
)


def _reason_groups_html(reasons: Sequence[KeyReason]) -> str:
    """Return the three titled reason lists, skipping empty ones; ids follow input order."""
    blocks = []
    for kind, title in _REASON_GROUPS:
        items = "".join(
            key_reason_html(reason, number)
            for number, reason in enumerate(reasons, start=1)
            if reason.kind == kind
        )
        if items:
            blocks.append(
                f'<div class="bb-rec-group" data-kind="{kind}">'
                f'<span class="bb-caps bb-rec-heading">{escape(title)}</span>'
                f'<ul class="bb-reasons">{items}</ul></div>'
            )
    return "".join(blocks)


def recommendation_section(recommendation: Recommendation | None) -> Markup:
    """Return section 1 with the decision, headline, reasons and conditions."""
    if recommendation is None:
        return _section(
            "recommendation",
            "Recommendation",
            '<p class="bb-small bb-muted">No recommendation was produced.</p>',
        )
    decision = recommendation.decision.value
    decision_label = _DECISION_LABELS.get(decision, decision.replace("_", " ").title())
    decision_line = (
        '<div class="bb-decision-line">'
        f'<span class="bb-badge bb-decision" data-decision="{escape(decision)}">'
        f"{escape(decision_label)}</span>"
    )
    if recommendation.proposed_limit:
        decision_line += (
            '<span class="bb-small bb-muted">Proposed limit '
            f'<strong class="bb-score-value">{escape(recommendation.proposed_limit)}</strong>'
            "</span>"
        )
    decision_line += "</div>"
    headline = (
        f'<p class="bb-headline">{escape(recommendation.headline)}</p>'
        if recommendation.headline
        else ""
    )
    reasons_block = _reason_groups_html(recommendation.key_reasons)
    conditions = "".join(f"<li>{escape(condition)}</li>" for condition in recommendation.conditions)
    conditions_block = (
        f'<span class="bb-caps">Conditions</span><ol class="bb-conditions">{conditions}</ol>'
        if conditions
        else ""
    )
    confidence_block = (
        f'<p class="bb-small bb-muted">{escape(recommendation.confidence_note)}</p>'
        if recommendation.confidence_note
        else ""
    )
    body = Markup(
        f'<div class="bb-recommendation">{decision_line}{headline}{reasons_block}'
        f"{conditions_block}{confidence_block}</div>"
    )
    return _section("recommendation", "Recommendation", body)


def _resolve_groups(
    facts: Mapping[str, VerifiedFact], fact_groups: Sequence[FactGroup]
) -> list[tuple[FactCategory, list[str]]]:
    """Return non-empty fact groups, appending any facts not listed by a group."""
    groups: list[tuple[FactCategory, list[str]]] = []
    seen: set[str] = set()
    for group in fact_groups:
        fact_ids = [
            fact_id for fact_id in group.fact_ids if fact_id in facts and fact_id not in seen
        ]
        if fact_ids:
            groups.append((group.category, fact_ids))
            seen.update(fact_ids)
    leftovers: dict[FactCategory, list[str]] = {}
    for fact_id, fact in facts.items():
        if fact_id not in seen:
            leftovers.setdefault(fact.category, []).append(fact_id)
    groups.extend(leftovers.items())
    return groups


def _winner_ids(report: Report) -> dict[str, str]:
    """Map each conflicted fact id to the id of the fact that overruled it."""
    winners: dict[str, str] = {}
    for fact in report.facts.values():
        for note in fact_field(fact, "conflicts"):
            winners.setdefault(note.fact_id, fact.fact_id)
    for fact_id, fact in report.facts.items():
        if conflicted_fact(fact) and fact_id not in winners and fact.verification is not None:
            found = re.match(r"conflicted with (\w+)", fact.verification.notes)
            if found:
                winners[fact_id] = found.group(1)
    return winners


def _fact_html(fact: VerifiedFact, winners: Mapping[str, str] | None = None) -> Markup:
    """Return one fact list item with its id anchor and citation chip."""
    fact_id = escape(fact.fact_id)
    text = statement_with_id_html(fact.statement, fact.fact_id, fact.citations, fact.verification)
    if conflicted_fact(fact):
        winner = (winners or {}).get(fact.fact_id)
        note = (
            f"overruled by {winner} (source priority)" if winner else "overruled (source priority)"
        )
        text = Markup(
            f'{text} <span class="bb-badge" data-status="conflicted">conflicted</span>'
            f' <span class="bb-small bb-muted bb-overruled">{escape(note)}</span>'
        )
        return Markup(
            f'<li class="bb-fact bb-stmt bb-fact-conflicted" id="fact-{fact_id}" '
            f'data-ref="{fact_id}">{text}</li>'
        )
    text = Markup(f"{text}{conflict_badge_html(fact_field(fact, 'conflicts'))}")
    return Markup(
        f'<li class="bb-fact bb-stmt" id="fact-{fact_id}" data-ref="{fact_id}">{text}</li>'
    )


def _fact_group_html(
    category: FactCategory,
    fact_ids: Sequence[str],
    facts: Mapping[str, VerifiedFact],
    id_prefix: str = "group",
    winners: Mapping[str, str] | None = None,
) -> Markup:
    """Return one category group of facts."""
    items = "".join(_fact_html(facts[fact_id], winners) for fact_id in fact_ids)
    category_key = escape(category.value)
    return Markup(
        f'<div class="bb-group" id="{id_prefix}-{category_key}">'
        f'<h3 class="bb-h3">{escape(humanise_category(category))}</h3>'
        f'<ul class="bb-facts">{items}</ul></div>'
    )


def rules_table_html(
    rules: Sequence[RuleResult], slots: Mapping[str, InputSlot] | None = None
) -> Markup:
    """Return the "Policy rule results" table, or nothing when the bank defines no rules."""
    if not rules:
        return Markup("")
    rows = "".join(str(rule_row_html(rule, slots)) for rule in rules)
    return Markup(
        '<div class="bb-table-wrap" id="rules"><table class="bb-table bb-rules">'
        "<caption>Policy rule results</caption>"
        '<thead><tr><th scope="col">Rule</th><th scope="col">Inputs</th>'
        '<th scope="col">Result</th><th scope="col">Lean</th></tr></thead>'
        f"<tbody>{rows}</tbody></table></div>"
    )


def scores_section(
    scores: Sequence[ScoreResult],
    score_specs: Mapping[str, ScoreSpec] | None = None,
    rules: Sequence[RuleResult] = (),
) -> Markup:
    """Return section 2: one dotted-leader line per policy score, then the rule results table."""
    specs = score_specs or {}
    items = "".join(
        score_statement_html(
            score,
            name=specs[score.score_id].name if score.score_id in specs else None,
            grades=specs[score.score_id].grades if score.score_id in specs else None,
            siblings=scores,
        )
        for score in scores
    )
    body = (
        Markup(f'<ul class="bb-scores">{items}</ul>')
        if items
        else Markup('<p class="bb-small bb-muted">No policy scores were computed.</p>')
    )
    return _section(
        "scores", "Policy scores", Markup(f"{body}{rules_table_html(rules, slot_index(specs))}")
    )


def pinned_fact_ids(report: Report) -> set[str]:
    """Fact ids the recommendation, score bindings, inferences or concerns point at."""
    pinned: set[str] = set()
    if report.recommendation is not None:
        for reason in report.recommendation.key_reasons:
            pinned.update(reason.fact_ids)
    for score in report.scores:
        for bound in score.inputs:
            pinned.update([bound.fact_id, *bound.derived_from])
    for inference in report.inferences:
        pinned.update(inference.fact_ids)
    for concern in report.concerns:
        pinned.update(concern.fact_ids)
    return pinned


def _rating_fact_ids(report: Report) -> set[str]:
    """Ids of facts cited from a rating-agency rationale."""
    rating_docs = {
        document.doc_id
        for document in report.documents
        if document.kind is DocumentKind.rating_rationale
    }
    return {
        fact_id
        for fact_id, fact in report.facts.items()
        if any(citation.doc_id in rating_docs for citation in fact.citations)
    }


def _display_rank(
    fact: VerifiedFact, pinned: set[str], rating: set[str]
) -> tuple[bool, bool, int, int, int]:
    return (
        fact.fact_id not in pinned,
        fact.fact_id not in rating,
        -fact_field(fact, "importance"),
        _SCOPE_RANK[fact_field(fact, "scope")],
        -len(fact.citations),
    )


def split_facts_by_importance(
    report: Report,
    min_importance: int,
    max_per_category: int = DEFAULT_MAX_PER_CATEGORY,
) -> tuple[dict[str, VerifiedFact], dict[str, VerifiedFact]]:
    """Return (main, appendix) facts, both in report order.

    Main holds every pinned fact plus, per category, the best-ranked facts with importance >=
    threshold up to `max_per_category` (0 or less means no cap).
    """
    pinned = pinned_fact_ids(report)
    rating = _rating_fact_ids(report)
    live = {fact_id: fact for fact_id, fact in report.facts.items() if not conflicted_fact(fact)}
    candidates: dict[FactCategory, list[VerifiedFact]] = {}
    for fact_id, fact in live.items():
        floor = min_importance - (RATING_IMPORTANCE_ALLOWANCE if fact_id in rating else 0)
        if fact_field(fact, "importance") >= floor or fact_id in pinned:
            candidates.setdefault(fact.category, []).append(fact)
    chosen = set(pinned) & set(live)
    for facts in candidates.values():
        ranked = sorted(facts, key=lambda fact: _display_rank(fact, pinned, rating))
        chosen.update(
            fact.fact_id for fact in ranked[: max_per_category if max_per_category > 0 else None]
        )
    main = {fact_id: fact for fact_id, fact in live.items() if fact_id in chosen}
    appendix = {fact_id: fact for fact_id, fact in live.items() if fact_id not in main}
    return main, appendix


def _fact_blocks(
    report: Report, facts: Mapping[str, VerifiedFact], id_prefix: str = "group"
) -> list[Markup]:
    groups = _resolve_groups(facts, report.fact_groups)
    winners = _winner_ids(report)
    return [_fact_group_html(category, ids, facts, id_prefix, winners) for category, ids in groups]


def facts_section(
    report: Report,
    min_importance: int = DEFAULT_MIN_IMPORTANCE,
    max_per_category: int = DEFAULT_MAX_PER_CATEGORY,
) -> Markup:
    """Return section 3 with the capped important and referenced facts grouped by category."""
    main, _ = split_facts_by_importance(report, min_importance, max_per_category)
    blocks = _fact_blocks(report, main)
    body = (
        Markup("".join(blocks))
        if blocks
        else Markup('<p class="bb-small bb-muted">No verified facts were available.</p>')
    )
    return _section("facts", "Relevant important facts", body)


def appendix_section(
    report: Report,
    min_importance: int = DEFAULT_MIN_IMPORTANCE,
    max_per_category: int = DEFAULT_MAX_PER_CATEGORY,
) -> Markup:
    """Return the final appendix with every other verified fact, or nothing when none remain."""
    _, rest = split_facts_by_importance(report, min_importance, max_per_category)
    rest = {
        **rest,
        **{fact_id: fact for fact_id, fact in report.facts.items() if conflicted_fact(fact)},
    }
    if not rest:
        return Markup("")
    body = Markup("".join(_fact_blocks(report, rest, "appendix-group")))
    return _section("appendix", "Appendix: other verified facts", body)


def shown_fact_ids(
    report: Report,
    min_importance: int = DEFAULT_MIN_IMPORTANCE,
    max_per_category: int = DEFAULT_MAX_PER_CATEGORY,
) -> dict[str, list[str]]:
    """Fact ids shown in the main facts section and in the appendix, in report order."""
    main, rest = split_facts_by_importance(report, min_importance, max_per_category)
    conflicted = [fact_id for fact_id, fact in report.facts.items() if conflicted_fact(fact)]
    return {"main": list(main), "appendix": [*rest, *conflicted]}


def inferences_section(inferences: Sequence[Inference]) -> Markup:
    """Return section 4 with the inferences drawn from verified facts."""
    blocks = "".join(inference_html(inference) for inference in inferences)
    body = (
        Markup(blocks)
        if blocks
        else Markup('<p class="bb-small bb-muted">No inferences were drawn.</p>')
    )
    return _section("inferences", "Inferences", body)


def concerns_section(concerns: Sequence[Concern]) -> Markup:
    """Return section 5 with the adversary stage's open concerns."""
    blocks = "".join(concern_html(concern) for concern in concerns if not concern.found)
    body = (
        Markup(blocks) if blocks else Markup('<p class="bb-small bb-muted">No open concerns.</p>')
    )
    return _section("concerns", "Open concerns", body)


def audit_footer_html(report: Report) -> Markup:
    """Return the document footer summarising the run and its audit counters."""
    audit = report.audit
    policy_state = "approved" if report.policy_approved else "unapproved"
    policy_version = audit.policy_version or report.bank_id or "policy"
    left = f"BusyBee · run {report.run_id} · policy {policy_version} ({policy_state})"
    if audit.lean_toolchain:
        left += f" · Lean {audit.lean_toolchain}"
    counters = [
        f"{len(report.facts)} facts",
        f"{len(report.scores)} scores",
        *([f"{len(report.rule_results)} policy rules"] if report.rule_results else []),
        f"{len(report.inferences)} inferences",
        f"{len(report.concerns)} concerns",
    ]
    if audit.decision_override is not None:
        counters.append("decision set by policy rules")
    if audit.llm_calls:
        counters.insert(0, f"{audit.llm_calls} LLM calls")
    return Markup(
        '<footer class="bb-doc-footer">'
        f"<span>{escape(left)}</span><span>{escape(' · '.join(counters))}</span>"
        "</footer>"
    )
